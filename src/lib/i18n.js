export function translate(lang, key, params) {
  const dict = dicts[lang] || dicts.en;
  let str = dict[key] ?? dicts.en[key] ?? key;
  if (params) {
    for (const k of Object.keys(params)) {
      str = str.split(`{${k}}`).join(params[k]);
    }
  }
  return str;
}